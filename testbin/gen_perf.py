#!/usr/bin/env python3
"""Generate a large C corpus for the performance test.

    python3 testbin/gen_perf.py [count] [output.c]

Each function has a different shape (loop, branch, array walk, bit mixing,
XOR buffer) so the analysis work per function is representative instead of
1200 copies of the same trivial body.
"""

from __future__ import annotations

import sys

SHAPES = (
    # arithmetic + branch
    """
int fn_@@N@@(int a, int b) {
    int r = a * 3 + b * 7 - (a ^ b);
    if (r > 100) r -= 17; else r += 23;
    return r % 97;
}
""",
    # loop with array walk
    """
int fn_@@N@@(int *buf, int len) {
    int sum = 0, i;
    for (i = 0; i < len; i++) sum += buf[i] * (i + 1);
    return sum;
}
""",
    # XOR decode loop
    """
void fn_@@N@@(unsigned char *data, int len, unsigned char key) {
    int i;
    for (i = 0; i < len; i++) data[i] ^= key;
}
""",
    # nested conditions
    """
int fn_@@N@@(int a, int b, int c) {
    if (a > b) {
        if (b > c) return a - c;
        if (a > c) return c + b;
        return a ^ b;
    }
    if (c > a) return a | b | c;
    return (a << 2) ^ (b >> 1);
}
""",
    # switch / state machine
    """
int fn_@@N@@(int state, int x) {
    switch (state) {
    case 0: return x + 1;
    case 1: return x * 3;
    case 2: return x ^ 0x5A;
    case 3: return x - 7;
    case 4: return x << 1;
    default: return x;
    }
}
""",
    # bit twiddling
    """
int fn_@@N@@(int x) {
    x = (x & 0x0F0F0F0F) + ((x >> 4) & 0x0F0F0F0F);
    x = (x & 0x00FF00FF) + ((x >> 8) & 0x00FF00FF);
    return (x & 0xFFFF) + ((x >> 16) & 0xFFFF);
}
""",
)


def main():
    count = int(sys.argv[1]) if len(sys.argv) > 1 else 1200
    out = sys.argv[2] if len(sys.argv) > 2 else "perf.c"
    lines = ["/* generated by testbin/gen_perf.py */", ""]
    for i in range(count):
        lines.append(SHAPES[i % len(SHAPES)].replace("@@N@@", str(i)))
    lines.append("")
    lines.append("int main(void) { return 0; }")
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print("wrote %s (%d functions)" % (out, count))


if __name__ == "__main__":
    main()
